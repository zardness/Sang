export const UNIVERSE: UniverseCompany[] = RAW.map(([ticker, name, sector]) => ({ ticker, name, market: "코스피", sector }));
export const findUniverse = (t: string) => UNIVERSE.find((c) => c.ticker === t);
export const SECTORS = [...new Set(UNIVERSE.map((c) => c.sector))];

/** 질문 속 기업 이름 찾기. "SK"와 "SK하이닉스"처럼 겹치면 더 긴 이름을 고릅니다. */
export function namedCompanies(text: string) {
  const t = text.replace(/\s/g, "").toLowerCase();
  const hits = UNIVERSE.filter((c) => t.includes(c.name.toLowerCase()));
  return hits.filter((c) => !hits.some((o) => o !== c && o.name.length > c.name.length && o.name.toLowerCase().includes(c.name.toLowerCase())));
}
